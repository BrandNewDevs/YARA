// Copies ml/prompt.md into a TS module so the app runs the prompt the evals test.
import { readFileSync, writeFileSync } from 'node:fs';

const prompt = readFileSync(new URL('../ml/prompt.md', import.meta.url), 'utf8');
const out = `// Generated by scripts/gen-prompt.mjs from ml/prompt.md. Do not edit.\nexport const CHAT_PROMPT = ${JSON.stringify(prompt)};\n`;
writeFileSync(new URL('../src/assistant/prompt.generated.ts', import.meta.url), out);
